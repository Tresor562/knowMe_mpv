const CANONICAL_BY_LOWER = new Map(
  META_NLLB_LOCALES.map((locale) => [locale.toLowerCase(), locale] as const)
);

const RTL_SCRIPTS = new Set(['Arab', 'Hebr']);

export function isSupportedLocale(value: unknown): value is SupportedLocale {
  return typeof value === 'string' && CANONICAL_BY_LOWER.has(value.toLowerCase());
}

export function resolveSupportedLocale(value: unknown): SupportedLocale | null {
  if (typeof value !== 'string') return null;
  const normalized = value.trim().replace(/_/g, '-');
  if (!normalized) return null;

  const exact = CANONICAL_BY_LOWER.get(normalized.toLowerCase());
  if (exact) return exact;

  const alias = ALIASES[normalized.toLowerCase()];
  if (alias) return alias;

  const [language] = normalized.toLowerCase().split('-');
  return ALIASES[language] ?? null;
}

export function normalizeLocale(
  value: unknown,
  fallback: SupportedLocale = DEFAULT_LOCALE
): SupportedLocale {
  return resolveSupportedLocale(value) ?? fallback;
}

export function resolveTextDirection(locale: string | null | undefined): TextDirection {
  const resolved = resolveSupportedLocale(locale);
  if (!resolved) return 'ltr';
  const script = resolved.split('-')[1];
  return script && RTL_SCRIPTS.has(script) ? 'rtl' : 'ltr';
}

export function localeDisplayName(
  locale: SupportedLocale,
  displayLocale: SupportedLocale = DEFAULT_LOCALE
) {
  try {
    const ui = displayLocale === 'fr' || displayLocale === 'en' ? displayLocale : 'en';
    const names = new Intl.DisplayNames([ui], { type: 'language' });
    return names.of(locale) || locale;
  } catch {
    return locale;
  }
}
